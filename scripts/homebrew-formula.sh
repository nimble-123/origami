#!/bin/sh
# Writes the Homebrew formula for one release to stdout.
#
#   scripts/homebrew-formula.sh VERSION DIR
#
# DIR holds the release binaries and their .sha256 files
# (origami-<version>-<triple> and origami-<version>-<triple>.sha256).
# The release workflow commits the result to nimble-123/homebrew-tap as
# Formula/origami.rb; users install with `brew install nimble-123/tap/origami`.
set -eu
version=$1
dir=$2
repo=${ORIGAMI_REPO:-nimble-123/origami}
base="https://github.com/${repo}/releases/download/v${version}"

# The checksum of one target, validated. Called as `x=$(sum TRIPLE) || exit 1`
# before anything is printed: an `exit` inside a command substitution inside
# the heredoc would only end that substitution.
sum() {
  f="$dir/origami-${version}-$1.sha256"
  [ -f "$f" ] || { echo "missing $f" >&2; return 1; }
  s=$(cut -d' ' -f1 < "$f")
  case $s in
    *[!0-9a-f]*) s= ;;
  esac
  [ ${#s} -eq 64 ] || { echo "invalid sha256 in $f" >&2; return 1; }
  printf '%s\n' "$s"
}

sum_arm_mac=$(sum aarch64-apple-darwin) || exit 1
sum_intel_mac=$(sum x86_64-apple-darwin) || exit 1
sum_arm_linux=$(sum aarch64-unknown-linux-gnu) || exit 1
sum_intel_linux=$(sum x86_64-unknown-linux-gnu) || exit 1

block() {
  printf '    url "%s/origami-%s-%s"\n' "$base" "$version" "$1"
  printf '    sha256 "%s"\n' "$2"
}

cat <<RUBY
# Generated by scripts/homebrew-formula.sh for origami ${version}.
class Origami < Formula
  desc "Layout-only formatter for ABAP and CDS"
  homepage "https://nimble-123.github.io/origami/"
  version "${version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
$(block aarch64-apple-darwin "$sum_arm_mac" | sed 's/^/  /')
    end
    on_intel do
$(block x86_64-apple-darwin "$sum_intel_mac" | sed 's/^/  /')
    end
  end

  on_linux do
    on_arm do
$(block aarch64-unknown-linux-gnu "$sum_arm_linux" | sed 's/^/  /')
    end
    on_intel do
$(block x86_64-unknown-linux-gnu "$sum_intel_linux" | sed 's/^/  /')
    end
  end

  def install
    bin.install Dir["origami-*"].first => "origami"
  end

  test do
    assert_match "origami #{version}", shell_output("#{bin}/origami --version")
    (testpath/"z.prog.abap").write "lv_a   =   1.\n"
    system bin/"origami", "--no-config", "z.prog.abap"
    assert_equal "lv_a = 1.\n", (testpath/"z.prog.abap").read
  end
end
RUBY
